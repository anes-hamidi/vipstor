import 'package:drift/drift.dart';

// Offline Sync Queue Table for Driver Collections & Deliveries
class OfflineSyncQueue extends Table {
  TextColumn get clientId => text()(); // UUID generated by device
  TextColumn get entityType => text()(); // 'delivery_record', 'wallet_collection'
  TextColumn get payloadJson => text()(); // Serialized arguments
  DateTimeColumn get createdAt => dateTime()();
  BoolColumn get isSynced => boolean().withDefault(const Constant(false))();
  IntColumn get retryCount => integer().withDefault(const Constant(0))();

  @override
  Set<Column> get primaryKey => {clientId};
}

// Local Cached Products Table
class LocalCachedProducts extends Table {
  TextColumn get id => text()();
  TextColumn get nameAr => text()();
  TextColumn get nameFr => text()();
  TextColumn get category => text()();
  TextColumn get unit => text()();
  IntColumn get packSize => integer()();
  IntColumn get lastUnitCost => integer()();
  IntColumn get availableQty => integer()();
  BoolColumn get active => boolean()();
  TextColumn get barcodesJson => text()();
  TextColumn get pricesJson => text()();

  @override
  Set<Column> get primaryKey => {id};
}
